-- Bucket público de fotos
insert into storage.buckets (id,name,public)
values ('produtos','produtos',true)
on conflict (id) do update set public=true;

drop policy if exists "Fotos públicas" on storage.objects;
drop policy if exists "Dono envia fotos" on storage.objects;
drop policy if exists "Dono remove fotos" on storage.objects;

create policy "Fotos públicas" on storage.objects for select to public using (bucket_id='produtos');
create policy "Dono envia fotos" on storage.objects for insert to authenticated
with check (
  bucket_id='produtos'
  and exists (select 1 from public.perfis p where p.id=(select auth.uid()) and p.role='dono')
);
create policy "Dono remove fotos" on storage.objects for delete to authenticated
using (
  bucket_id='produtos'
  and exists (select 1 from public.perfis p where p.id=(select auth.uid()) and p.role='dono')
);

