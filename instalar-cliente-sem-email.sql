grant execute on function public.registrar_pedido_cliente(uuid,integer,text,text,text,text,text,text,text,text,numeric,numeric,numeric,jsonb) to anon, authenticated;
grant execute on function public.listar_pedidos_cliente(uuid) to anon, authenticated;

